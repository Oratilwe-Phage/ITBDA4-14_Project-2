# 1.2. MAPPER IMPLEMENTATION

# The mapper function reads a single document, scans each line
# for the keyword and emits key-value pairs containing the
# document name, row number and column position.

mapper <- function(file_path, keyword) {
  
  # Reading the document line by line
  lines <- readLines(file_path, warn = FALSE)
  
  mapped_results <- list()
  
  # Examining each line in the document
  for (row_idx in seq_along(lines)) {
    
    current_line <- lines[row_idx]
    
    # Converting  the line to lowercase
    lower_line <- tolower(current_line)
    
    # Finding all keyword positions in the current line
    matches <- gregexpr(
      keyword,
      lower_line,
      fixed = TRUE
    )[[1]]
    
    # Checking  whether a match was found
    if (matches[1] != -1) {
      
      # Process every occurrence of the keyword
      for (col_idx in matches) {
        
        # Generate key-value pair
        kv_pair <- list(
          
          key = keyword,
          
          value = list(
            document = basename(file_path),
            row = row_idx,
            column = col_idx,
            
            matched_text = substr(
              current_line,
              col_idx,
              col_idx + nchar(keyword) - 1
            )
          )
        )
        
        # Store the mapped result
        mapped_results[[length(mapped_results) + 1]] <- kv_pair
      }
    }
  }
  
  return(mapped_results)
}



# 1.3. REDUCER IMPLEMENTATION

# The reducer aggregates all mapped values grouped by the target keyword.
# It simulates the Shuffle and Sort phase before producing the final results.

reducer <- function(keyed_data) {
  
  # Initialise aggregated results
  aggregated_results <- list()
  
  # Shuffle and Sort phase
  for (item in keyed_data) {
    
    k <- item$key
    v <- item$value
    
    # Creating a group for the keyword if it does not exist
    if (is.null(aggregated_results[[k]])) {
      aggregated_results[[k]] <- list()
    }
    
    # Adding the value to the corresponding keyword group
    aggregated_results[[k]][[
      length(aggregated_results[[k]]) + 1
    ]] <- v
  }
  
  return(aggregated_results)
}



